# Кортеж с названием дней недели
days_of_week = ("Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье")

# Запрашиваем количество выходных
try:
    num_weekends = int(input("Сколько выходных на неделе вы хотите? "))

    # Проверяем, чтобы число было корректным (от 0 до 7)
    if 0 <= num_weekends <= 7:
        # Выходные дни: берем последние n элементов
        # Если num_weekends = 0, срез [7:] вернет пустой список
        weekends = days_of_week[len(days_of_week) - num_weekends:]
        
        # Рабочие дни: берем всё, кроме последних n элементов
        work_days = days_of_week[:len(days_of_week) - num_weekends]

        # Выводим результаты
        print(f"Ваши выходные дни: {', '.join(weekends)}")
        print(f"Ваши рабочие дни: {', '.join(work_days)}")
    else:
        print("Ошибка: в неделе всего 7 дней. Введите число от 0 до 7.")

except ValueError:
    print("Ошибка: пожалуйста, введите целое число.")